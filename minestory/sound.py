"""Deterministic original procedural SFX. No bundled Minecraft audio or music."""
from __future__ import annotations
from pathlib import Path
import hashlib
import math
import subprocess
import wave
from typing import Any
import numpy as np

SAMPLE_RATE = 48000
_NAMES = {"walk": "step", "run": "step", "place": "place", "give": "item", "receive": "item",
          "discover": "discovery", "surprise": "surprise", "fall": "impact", "jump": "whoosh",
          "explode": "explosion", "appear": "item", "reveal": "discovery"}


def _effect(name: str, sample_rate: int = SAMPLE_RATE) -> np.ndarray:
    seed = int.from_bytes(hashlib.sha256(name.encode()).digest()[:4], "little")
    rng = np.random.default_rng(seed)
    duration = {"step": .11, "impact": .24, "explosion": .7, "discovery": .55,
                "surprise": .4, "whoosh": .32, "place": .15, "item": .23}.get(name, .22)
    t = np.arange(round(duration * sample_rate)) / sample_rate
    noise = rng.standard_normal(len(t))
    if name in {"step", "place", "impact", "explosion"}:
        signal = .45 * noise + .55 * np.sin(2 * np.pi * (95 if name == "step" else 65) * t)
        envelope = np.exp(-t * (28 if name == "step" else 12)) * np.minimum(1, t * 900)
    elif name == "whoosh":
        signal = np.convolve(noise, np.ones(12) / 12, "same")
        envelope = np.sin(np.pi * t / duration) ** 2
    else:
        base = {"item": 660, "discovery": 523.25, "surprise": 392}.get(name, 440)
        f = base * (1 + .45 * t / duration)
        phase = 2 * np.pi * np.cumsum(f) / sample_rate
        signal = .7 * np.sin(phase) + .2 * np.sin(phase * 1.5) + .1 * np.sin(phase * 2)
        envelope = np.minimum(1, t * 150) * np.exp(-t * 6)
    result = signal * envelope
    peak = np.max(np.abs(result)) or 1
    return result / peak * .18


def _write_wav(path: Path, values: np.ndarray, sample_rate: int = SAMPLE_RATE) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with wave.open(str(path), "wb") as handle:
        handle.setnchannels(1)
        handle.setsampwidth(2)
        handle.setframerate(sample_rate)
        handle.writeframes((np.clip(values, -1, 1) * 32767).astype("<i2").tobytes())


def build_soundtrack(storyboard: dict[str, Any], duration: float, output_path: str | Path,
                     **kwargs: Any) -> dict[str, Any]:
    result = np.zeros(math.ceil(duration * SAMPLE_RATE), dtype=np.float32)
    events = []
    for scene in storyboard.get("scenes", []):
        scene_start = float(scene.get("start", 0))
        relative_events = "sound_events" in scene
        explicit = scene.get("sound_events", scene.get("sound_effects", scene.get("sfx", [])))
        if not isinstance(explicit, list):
            explicit = []
        for event in explicit:
            if isinstance(event, str):
                event = {"name": event, "time": scene_start}
            name = str(event.get("name", event.get("type", "item")))
            at = float(event.get("time", event.get("at", 0 if relative_events else scene_start)))
            if relative_events:
                at += scene_start
            # Explicit 'offset' is relative; all 'time'/'at' are global seconds.
            if "offset" in event:
                at = scene_start + float(event["offset"])
            events.append({"name": _NAMES.get(name, name), "time": at, "gain": max(0., min(1., float(event.get("gain", 1.))))})
        if not explicit:
            for action in scene.get("actions", []):
                if not isinstance(action, dict):
                    continue
                kind = action.get("type", action.get("action", ""))
                if kind in _NAMES:
                    events.append({"name": _NAMES[kind], "time": float(action.get("start", scene_start))})
    # Never let repeated autogenerated actions flood the narrator.
    last_time = -10.
    accepted = []
    for event in sorted(events, key=lambda x: x["time"]):
        at = max(0., event["time"])
        if at >= duration or at - last_time < .24:
            continue
        values = _effect(event["name"]) * event.get("gain", 1.)
        offset = round(at * SAMPLE_RATE)
        length = min(len(values), len(result) - offset)
        if length > 0:
            result[offset:offset+length] += values[:length]
            accepted.append({**event, "time": at})
            last_time = at
    path = Path(output_path)
    _write_wav(path, result)
    return {"path": str(path), "events": accepted, "count": len(accepted),
            "license": "CC0-1.0: original procedural waveforms generated by MineStory",
            "music": False, "peak": float(np.max(np.abs(result))) if len(result) else 0.}


def mix_audio(narration: str | Path, effects: str | Path, output_path: str | Path,
              duration: float, **kwargs: Any) -> dict[str, Any]:
    """Unity-gain narration; quiet SFX duck under speech. No retiming or synthesis."""
    path = Path(output_path)
    path.parent.mkdir(parents=True, exist_ok=True)
    graph = ("[0:a]aresample=48000,asplit=2[voice][detector];"
             "[1:a]aresample=48000,volume=0.35[fx];"
             "[fx][detector]sidechaincompress=threshold=0.025:ratio=10:attack=8:release=180[ducked];"
             "[voice][ducked]amix=inputs=2:duration=first:dropout_transition=0:normalize=0,"
             "alimiter=limit=0.98:level=false:latency=true[out]")
    result = subprocess.run(["ffmpeg", "-y", "-hide_banner", "-nostdin", "-i", str(Path(narration).resolve()),
                             "-i", str(Path(effects).resolve()), "-filter_complex", graph,
                             "-map", "[out]", "-t", str(duration), "-ac", "2", "-c:a", "pcm_s16le", str(path)],
                            text=True, capture_output=True)
    if result.returncode:
        raise RuntimeError(f"Falha ao mixar som: {result.stderr[-2000:]}")
    return {"path": str(path), "narration_speed": 1., "narration_gain": 1.,
            "effects_gain": .35, "sidechain_ducking": True,
            "limiter": .98, "sample_rate": SAMPLE_RATE, "music": False}
